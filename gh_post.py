#!/usr/bin/env python3
"""Отправить текст на GitHub (комментарий, правку комментария, описание PR или тикета) через гейт кодировки.

Боты пишут в тикеты по-русски, и не раз комментарий доходил до GitHub строкой знаков «?»:
текст по дороге проходил через однобайтовую кодовую страницу (консоль Windows, аргумент
командной строки, неверно настроенный shell), и каждая буква, которой там нет, становилась «?».
Прочитать такой комментарий нельзя, а исходный текст уже потерян. Скрипт закрывает обе дыры:

1. гейт: файл читается как строгий UTF-8, и текст отклоняется (код 2, ничего не отправлено),
   если в нём есть U+FFFD, буквальные `\\n` вместо переводов строк или похожие на кашу знаки
   вопроса («???», «?? ???? ???», заметная доля «?» среди букв) — вне блоков кода;
2. сверка: тело уходит файлом (`gh api -F body=@файл`, без командной строки), после отправки
   комментарий читается с GitHub и сравнивается с файлом; не совпало — комментарий
   переписывается из файла ещё раз, а если и это не помогло, удаляется, и скрипт выходит с кодом 1.

    python3 gh_post.py check <файл>
    python3 gh_post.py comment <owner/repo> <номер тикета или PR> <файл>
    python3 gh_post.py edit <owner/repo> <id комментария> <файл>
    python3 gh_post.py pr-body <owner/repo> <номер PR> <файл>
    python3 gh_post.py issue-body <owner/repo> <номер тикета> <файл>
    python3 gh_post.py issue <owner/repo> <файл> [--label <метка>]   # первая строка — заголовок, дальше тело
    python3 gh_post.py pr <owner/repo> <head> <base> <файл>   # первая строка — заголовок, дальше тело
    python3 gh_post.py scan <owner/repo> [--days 3]           # найти уже испорченные комментарии

`scan` перечисляет комментарии последних дней, которые гейт отклонил бы. То же самое каждые
расписанию делает janitor и пишет найденное в `projects/<проект>/MOJIBAKE.md`; испорченный
комментарий восстанавливает любой бот правкой `edit` того же комментария (по смыслу ASCII-остова,
соседних сообщений и учёта), и после этого он из файла пропадает сам.
"""
import json
import re
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timedelta, timezone

CODE_BLOCK = re.compile(r"```.*?(```|$)", re.S)
INLINE_CODE = re.compile(r"`[^`\n]*`")
CLAUDE_FOOTER = re.compile(
    r"\n*\s*(?:---\s*\n)?"
    r"(?:_Generated by \[Claude Code\]\(https://claude\.ai/code\)_|"
    r"🤖 Generated with \[Claude Code\]\(https://claude\.com/claude-code\))"
    r"(?:\n\[[^\]\n]+\]\(https?://[^)\n]+\))?\s*$"
)
# Три «?» подряд не пишет никто, а каша из подряд идущих «слов» из одних «?» — это
# буквы, которые потерялись по дороге.
QUESTION_RUN = re.compile(r"\?{3,}")
QUESTION_WORDS = re.compile(r"(?:\?{2,}[\s.,:;!()\-]+){2,}\?+")
GATE_MESSAGE = ("Текст для GitHub пишется файлом в UTF-8 с настоящими переводами строк и уходит "
                "только через gh_post.py (LUNOBOT.md § 2).")


# Буквальный `\n` вместо перевода строки. Часть пути Windows (`\\?\nul\`, `C:\new`, `dir\\name`) им
# не является: сразу перед ним обратная косая черта, `\\?` или отдельно стоящая буква диска `X:`
# (ложные срабатывания janitor на unxed/f4#1966 и unxed/f4#1969, 15-10-2026). Буква диска — одна
# буква, не хвост слова: «Files:\\n- a» остаётся порчей.
LITERAL_NEWLINE = re.compile(r"(?<!\\)(?<!\\\\\?)(?<!(?<![A-Za-z0-9_])[A-Za-z]:)\\n")


def prose(text):
    """Текст без блоков и вставок кода: в коде «???» и `\\n` — законное содержимое."""
    return INLINE_CODE.sub(" ", CODE_BLOCK.sub(" ", text))


def check_text(text):
    """Причина отказа или пустая строка, если текст можно отправлять."""
    if not text.strip():
        return "текст пуст"
    if "�" in text:
        return "в тексте символ замены U+FFFD: кодировка испорчена ещё до отправки"
    body = prose(text)
    if LITERAL_NEWLINE.search(body):
        return "в тексте буквальные \\n вместо переводов строк"
    if QUESTION_RUN.search(body) or QUESTION_WORDS.search(body):
        return "в тексте подряд идущие «?» на месте букв: кодировка испорчена"
    letters = sum(ch.isalpha() for ch in body)
    marks = body.count("?")
    if marks >= 5 and marks > 0.15 * (letters + marks):
        return "в тексте слишком много «?» относительно букв: похоже на испорченную кодировку"
    return ""


SIGNATURE = re.compile(r"^\*(Лунобот|Lunobot)-\d[^\n]*\*\s*$", re.M)
URL = re.compile(r"https?://\S+")
QUOTED = re.compile(r"(?s:<details>.*?</details>)|^>.*$", re.M)
CYRILLIC_SHARE = 0.3


def check_signature(text):
    """Причина отказа или пустая строка: написание подписи (§ 9) обязано совпадать с языком текста.

    Проверяется только подпись бота последней строкой тела. Язык текста — русский, если кириллица составляет не
    меньше трети его букв вне кода и ссылок; иначе — латиница. Текст без подписи не проверяется (подпись нужна не
    везде), `scan` janitor это правило не применяет: оно только для отправки новых текстов.
    """
    matches = list(SIGNATURE.finditer(text))
    if not matches:
        return ""
    sig = matches[-1]
    # Дословные вставки (<details>…</details>, цитаты «> …») не решают язык: пересказ чужого текста ≠ язык сообщения.
    body = URL.sub(" ", QUOTED.sub(" ", prose(text[:sig.start()])))
    cyrillic = sum("\u0400" <= ch <= "\u04ff" for ch in body)
    letters = sum(ch.isalpha() for ch in body)
    if letters < 20:
        return ""
    russian = cyrillic >= CYRILLIC_SHARE * letters
    if russian and sig.group(1) != "Лунобот":
        return "текст русский, а подпись латиницей «Lunobot»: подпись пишется на языке текста (LUNOBOT.md § 9)"
    if not russian and sig.group(1) != "Lunobot":
        return "текст не русский, а подпись кириллицей «Лунобот»: подпись пишется на языке текста (LUNOBOT.md § 9)"
    return ""


def read_text(path):
    with open(path, "rb") as f:
        raw = f.read()
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError as err:
        raise SystemExit(f"отклонено: файл {path} не в UTF-8 ({err}). {GATE_MESSAGE}")


def normalize(text):
    return "\n".join(line.rstrip() for line in text.replace("\r\n", "\n").split("\n")).strip()


def same_text(stored, sent):
    """Дошло ли до GitHub то, что отправлено.

    Прокси облачной среды может дописать или переписать стандартный подвал Claude Code.
    До сравнения убираем его с обеих сторон, но сначала проверяем исходный текст целиком:
    испорченный подвал не должен маскироваться как служебная приписка.
    """
    stored, sent = normalize(stored), normalize(sent)
    if check_text(stored) or check_text(sent):
        return False

    def without_footers(text):
        while True:
            stripped = CLAUDE_FOOTER.sub("", text, count=1).strip()
            if stripped == text:
                return text
            text = stripped

    stored, sent = without_footers(stored), without_footers(sent)
    if stored == sent:
        return True
    return stored.startswith(sent) and check_text(stored[len(sent):]) in ("", "текст пуст")


def gh(*args, check=True):
    out = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8")
    if check and out.returncode != 0:
        raise SystemExit(f"gh {' '.join(args[:3])}: {out.stderr.strip()[:400]}")
    return out


def api(path, *args, check=True):
    out = gh("api", path, *args, check=check)
    if out.returncode != 0 or not out.stdout.strip():
        return None
    return json.loads(out.stdout)


def gate(path):
    text = read_text(path)
    reason = check_text(text) or check_signature(text)
    if reason:
        print(f"отклонено: {reason}. {GATE_MESSAGE}", file=sys.stderr)
        raise SystemExit(2)
    return text


def verify_comment(repo, comment, text, path):
    """Сравнить отправленное с файлом; при расхождении переписать, затем удалить."""
    cid = comment["id"]
    for attempt in range(2):
        got = api(f"repos/{repo}/issues/comments/{cid}")
        if got and same_text(got.get("body") or "", text):
            print(got.get("html_url", ""))
            return 0
        if attempt == 0:
            api(f"repos/{repo}/issues/comments/{cid}", "-X", "PATCH", "-F", f"body=@{path}", check=False)
    gh("api", "-X", "DELETE", f"repos/{repo}/issues/comments/{cid}", check=False)
    print(f"ошибка: GitHub хранит не тот текст, что в {path}; комментарий {cid} удалён. "
          "Проверь кодировку среды (UTF-8) и отправь заново.", file=sys.stderr)
    return 1


def verify_body(repo, kind, number, text, path):
    """Тело PR (kind="pulls") или тикета (kind="issues") на GitHub совпадает с файлом; иначе одна перезапись."""
    what = "описание PR" if kind == "pulls" else "тело тикета"
    for attempt in range(2):
        got = api(f"repos/{repo}/{kind}/{number}")
        if got and same_text(got.get("body") or "", text):
            print(got.get("html_url", ""))
            return 0
        if attempt == 0:
            api(f"repos/{repo}/{kind}/{number}", "-X", "PATCH", "-F", f"body=@{path}", check=False)
    print(f"ошибка: {what} {repo}#{number} не совпало с {path}; поправь его вручную "
          "из файла в UTF-8-среде.", file=sys.stderr)
    return 1


def verify_pr(repo, number, text, path):
    return verify_body(repo, "pulls", number, text, path)


def find_comment(repo, number, text):
    """Свежий комментарий тикета с таким же текстом (после обрыва ответа GitHub)."""
    comments = api(f"repos/{repo}/issues/{number}/comments?per_page=100&sort=created&direction=desc",
                   check=False) or []
    for c in comments[-10:][::-1]:
        if same_text(c.get("body") or "", text):
            return c
    return None


def post_comment(repo, number, path):
    text = gate(path)
    comment = None
    for attempt in range(3):
        # Прокси и GitHub иногда обрывают ответ («unexpected end of JSON input», 502):
        # комментарий при этом может уже быть создан, поэтому перед повтором ищем его.
        out = gh("api", f"repos/{repo}/issues/{number}/comments", "-F", f"body=@{path}", check=False)
        if out.returncode == 0 and out.stdout.strip():
            comment = json.loads(out.stdout)
            break
        comment = find_comment(repo, number, text)
        if comment:
            break
        time.sleep(3 * (attempt + 1))
    if not comment:
        raise SystemExit("комментарий не создан")
    return verify_comment(repo, comment, text, path)


def edit_comment(repo, cid, path):
    text = gate(path)
    comment = api(f"repos/{repo}/issues/comments/{cid}", "-X", "PATCH", "-F", f"body=@{path}")
    if not comment:
        raise SystemExit("комментарий не изменён")
    return verify_comment(repo, comment, text, path)


def pr_body(repo, number, path):
    text = gate(path)
    api(f"repos/{repo}/pulls/{number}", "-X", "PATCH", "-F", f"body=@{path}")
    return verify_pr(repo, number, text, path)


def issue_body(repo, number, path):
    text = gate(path)
    api(f"repos/{repo}/issues/{number}", "-X", "PATCH", "-F", f"body=@{path}")
    return verify_body(repo, "issues", number, text, path)


def parse_issue_args(args):
    """`<owner/repo> <файл> [--label <метка>]...` → (repo, path, labels) или None, если разбор не удался.

    Лишний или неизвестный аргумент, `--label` без значения — отказ, а не тихий пропуск:
    иначе тикет молча создаётся без метки, которую просили.
    """
    if len(args) < 2:
        return None
    labels = []
    rest = args[2:]
    while rest:
        if rest[0] != "--label" or len(rest) < 2 or not rest[1].strip() or rest[1].startswith("--"):
            return None
        labels.append(rest[1])
        rest = rest[2:]
    return args[0], args[1], labels


def create_issue(repo, path, labels):
    text = gate(path)
    title, _, body = text.partition("\n")
    title = title.strip()
    if not title:
        raise SystemExit("первая строка файла — заголовок тикета — пуста")
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".md", delete=False) as f:
        f.write(body.lstrip("\n"))
        body_path = f.name
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".txt", delete=False) as f:
        f.write(title)
        title_path = f.name
    extra = [x for label in labels for x in ("-f", f"labels[]={label}")]
    issue = api(f"repos/{repo}/issues", "-F", f"title=@{title_path}", "-F", f"body=@{body_path}", *extra)
    if not issue:
        raise SystemExit("тикет не создан")
    print(issue.get("html_url", ""))
    if normalize(issue.get("title", "")) != normalize(title):
        print(f"ошибка: заголовок тикета {issue.get('html_url')} не совпал с файлом", file=sys.stderr)
        return 1
    stored = {(item.get("name") or "").casefold() for item in issue.get("labels") or [] if isinstance(item, dict)}
    missing = [label for label in labels if label.casefold() not in stored]
    if missing:
        print(f"ошибка: у тикета {issue.get('html_url')} нет меток {', '.join(missing)}: "
              "проверь кодировку среды (UTF-8) и поставь метки вручную.", file=sys.stderr)
        return 1
    if not body.strip():
        # Пустое тело нечем сверять (same_text отвергает пустой текст): заголовок уже сверен.
        return 0
    return verify_body(repo, "issues", issue["number"], body.lstrip("\n"), body_path)


def create_pr(repo, head, base, path):
    text = gate(path)
    title, _, body = text.partition("\n")
    title = title.strip()
    if not title:
        raise SystemExit("первая строка файла — заголовок PR — пуста")
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".md", delete=False) as f:
        f.write(body.lstrip("\n"))
        body_path = f.name
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".txt", delete=False) as f:
        f.write(title)
        title_path = f.name
    pr = api(f"repos/{repo}/pulls", "-F", f"title=@{title_path}", "-f", f"head={head}",
             "-f", f"base={base}", "-F", f"body=@{body_path}")
    if not pr:
        raise SystemExit("PR не создан")
    if normalize(pr.get("title", "")) != normalize(title):
        print(f"ошибка: заголовок PR {pr.get('html_url')} не совпал с файлом", file=sys.stderr)
        return 1
    return verify_pr(repo, pr["number"], body.lstrip("\n"), body_path)


def scan(repo, days):
    since = (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ")
    found = 0
    page = 1
    while True:
        batch = api(f"repos/{repo}/issues/comments?since={since}&per_page=100&page={page}") or []
        for c in batch:
            reason = check_text(c.get("body") or "")
            if reason and reason != "текст пуст":
                found += 1
                print(f"{c['html_url']} ({c['user']['login']}, {c['created_at']}): {reason}")
        if len(batch) < 100:
            break
        page += 1
    if not found:
        print(f"{repo}: испорченных комментариев за {days} дн. нет")
    return 1 if found else 0


def main(argv):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="backslashreplace")
        except (AttributeError, ValueError):
            pass
    if not argv:
        print(__doc__)
        return 2
    cmd, args = argv[0], argv[1:]
    if cmd == "check" and len(args) == 1:
        gate(args[0])
        print("годится")
        return 0
    if cmd == "comment" and len(args) == 3:
        return post_comment(*args)
    if cmd == "edit" and len(args) == 3:
        return edit_comment(*args)
    if cmd == "pr-body" and len(args) == 3:
        return pr_body(*args)
    if cmd == "issue-body" and len(args) == 3:
        return issue_body(*args)
    if cmd == "issue":
        parsed = parse_issue_args(args)
        if parsed is None:
            print(__doc__)
            return 2
        return create_issue(*parsed)
    if cmd == "pr" and len(args) == 4:
        return create_pr(*args)
    if cmd == "scan" and args:
        days = 3
        if "--days" in args:
            days = int(args[args.index("--days") + 1])
        return scan(args[0], days)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
